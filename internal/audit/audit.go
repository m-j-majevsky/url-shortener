// Package audit реализует аудит запросов сервиса на основе паттерна «Наблюдатель».
//
// Роль наблюдателей (приёмников аудита) исполняют реализации интерфейса Observer:
// FileSink (запись в файл) и HTTPSink (отправка POST-запросом на удалённый сервер).
// Роль наблюдаемого объекта («субъекта») исполняет Broadcaster: он собирает
// зарегистрированных наблюдателей и рассылает им события аудита.
//
// Рассылка построена на каналах: события попадают в буферизованный входной канал,
// диспетчер раскладывает их по личным очередям наблюдателей, и у каждого
// наблюдателя работает ровно один фиксированный воркер. Такой дизайн исключает
// размножение горутин под нагрузкой и гонку Notify ↔ Close, свойственную схеме,
// где на каждый Notify создаётся новая горутина под WaitGroup.
//
// Если ни один приёмник не настроен, Broadcaster остаётся без наблюдателей,
// и его Notify фактически превращается в no-op: аудит отключён.
//
// Доставка событий — best-effort: гарантий доставки нет. При переполнении
// входного буфера, личных очередей наблюдателей или при вызове Notify после
// Close событие отбрасывается с записью в лог; совокупное число отброшенных
// событий доступно через метод Dropped и логируется при Close. Если когда-нибудь
// понадобится гарантированная доставка, буферов в памяти недостаточно —
// потребуется персистентная очередь между сервисом и приёмником.
package audit

import (
	"fmt"
	"sync"
	"sync/atomic"

	"go.uber.org/zap"
)

// Допустимые значения поля Action события аудита.
const (
	ActionShorten = "shorten" // создание короткой ссылки
	ActionFollow  = "follow"  // переход по короткой ссылке
)

// AuditEvent — событие аудита.
type AuditEvent struct {
	TS     int64  `json:"ts"`
	Action string `json:"action"`
	UserID string `json:"user_id"`
	URL    string `json:"url"`
}

// Observer — «наблюдатель»: приёмник событий аудита.
type Observer interface {
	Send(event AuditEvent) error
}

// Notifier — часть интерфейса «субъекта», необходимая хэндлерам:
// точка диспетчеризации событий аудита. Реализуется Broadcaster'ом.
type Notifier interface {
	Notify(event AuditEvent)
}

// Ёмкости каналов Broadcaster'а подобраны с расчётом на всплески нагрузки:
// входной буфер сглаживает пики запросов, личные очереди сглаживают
// замедление отдельных приёмников.
const (
	eventQueueSize   = 1024 // ёмкость входного канала событий
	observerQueueCap = 64   // ёмкость личной очереди каждого наблюдателя
)

// observerPipe — наблюдатель и его личная очередь событий.
type observerPipe struct {
	observer Observer
	queue    chan AuditEvent
}

// Broadcaster — «субъект» в паттерне «Наблюдатель»: рассылает события
// всем зарегистрированным приёмникам.
//
// Асинхронность обеспечивает фиксированный набор горутин: один диспетчер,
// читающий входной канал, и по одному воркеру на каждого наблюдателя.
// Медлительность одного приёмника не блокирует ни обработку запроса,
// ни доставку другим приёмникам. Ошибки отправки не прерывают доставку,
// а логируются.
type Broadcaster struct {
	events    chan AuditEvent
	pipes     []observerPipe
	wg        sync.WaitGroup
	closeOnce sync.Once

	// dropped — совокупное число событий, отброшенных с момента создания
	// субъекта: из-за переполнения буферов или вызова Notify после Close.
	// Атомарный, потому что инкрементируется из диспетчера и из вызывающих
	// Notify горутин одновременно.
	dropped atomic.Int64

	// mu защищает события и флаг closed: Close закрывает канал под блокировкой,
	// Notify отправляет событие только в незакрытый канал. Благодаря этому Notify
	// безопасно вызывать и во время graceful shutdown — даже когда server.Shutdown
	// завершился по таймауту и хэндлеры в полёте продолжают вызывать Notify.
	mu     sync.RWMutex
	closed bool

	log *zap.Logger // логгер; если nil — используется no-op
}

// NewBroadcaster создаёт субъект аудита с перечисленными наблюдателями
// и запускает фиксированные воркеры: диспетчер и по одному на наблюдателя.
func NewBroadcaster(log *zap.Logger, observers ...Observer) *Broadcaster {
	if log == nil {
		log = zap.NewNop()
	}

	b := &Broadcaster{
		events: make(chan AuditEvent, eventQueueSize),
		log:    log,
	}

	for _, obs := range observers {
		// nil-наблюдатель пропускаем: воркер для него не запускается, иначе он
		// упал бы паникой при первой же отправке (симметрично проверке в Notify).
		if obs == nil {
			continue
		}

		pipe := observerPipe{observer: obs, queue: make(chan AuditEvent, observerQueueCap)}
		b.pipes = append(b.pipes, pipe)

		// Воркер наблюдателя: последовательно отправляет события из его очереди.
		// Завершается, когда диспетчер закроет очередь и та опустеет.
		b.wg.Add(1)
		go func(p observerPipe) {
			defer b.wg.Done()
			for event := range p.queue {
				if err := p.observer.Send(event); err != nil {
					b.log.Error("ошибка отправки события аудита", zap.Error(err))
				}
			}
		}(pipe)
	}

	// Диспетчер нужен только при наличии наблюдателей: без них Notify — no-op,
	// читать входной канал некому.
	if len(b.pipes) > 0 {
		b.wg.Add(1)
		go b.dispatch()
	}

	return b
}

// dispatch читает входной канал и раскладывает события по очередям наблюдателей.
// Когда входной канал закрыт и опустошён, закрывает личные очереди наблюдателей
// и завершается.
func (b *Broadcaster) dispatch() {
	defer b.wg.Done()
	defer func() {
		for _, p := range b.pipes {
			close(p.queue)
		}
	}()

	for event := range b.events {
		for _, p := range b.pipes {
			select {
			case p.queue <- event:
			default:
				// Очередь конкретного наблюдателя переполнена: событие для него
				// отбрасываем, чтобы медленный приёмник не задерживал диспетчер
				// и доставку остальным приёмникам. Потеря фиксируется счётчиком.
				b.dropped.Add(1)
				b.log.Error("переполнена очередь наблюдателя аудита, событие отброшено",
					zap.String("sink", fmt.Sprintf("%T", p.observer)))
			}
		}
	}
}

// Notify асинхронно отправляет событие во все зарегистрированные приёмники.
// Метод никогда не блокирует хэндлер: если входной буфер переполнен, событие
// отбрасывается с записью в лог. Метод безопасно вызывать при отсутствии
// приёмников, на nil-получателе и после Close (в обоих последних случаях —
// no-op; отброшенное после Close событие учитывается в Dropped).
func (b *Broadcaster) Notify(event AuditEvent) {
	if b == nil || len(b.pipes) == 0 {
		return
	}

	b.mu.RLock()
	defer b.mu.RUnlock()
	if b.closed {
		// Событие после Close не доставляется: учитываем его как потерянное.
		b.dropped.Add(1)
		return
	}

	select {
	case b.events <- event:
	default:
		// Входной буфер переполнен: событие отбрасывается, чтобы не блокировать
		// хэндлер. Потеря фиксируется счётчиком.
		b.dropped.Add(1)
		b.log.Error("переполнена очередь событий аудита, событие отброшено",
			zap.Any("event", event))
	}
}

// Dropped возвращает совокупное число событий, отброшенных с момента создания
// субъекта: из-за переполнения входного буфера или личных очередей наблюдателей,
// а также при вызовах Notify после Close. Доставка событий — best-effort,
// поэтому счётчик — способ сделать потерю наблюдаемой.
func (b *Broadcaster) Dropped() int64 {
	if b == nil {
		return 0
	}
	return b.dropped.Load()
}

// Close останавливает приём новых событий и дожидается доставки накопившихся:
// диспетчер дораздаёт их наблюдателям, воркеры доотправляют, после чего
// Close разблокируется. Отброшенные при переполнении буферов события
// не восстанавливаются; если потери были, Close логирует их совокупное число
// (см. Dropped). Метод идемпотентен.
func (b *Broadcaster) Close() {
	if b == nil {
		return
	}
	b.closeOnce.Do(func() {
		b.mu.Lock()
		b.closed = true
		close(b.events)
		b.mu.Unlock()
	})
	b.wg.Wait()

	// Итоговая сводка о потерях: о совокупной потере событий стоит узнать
	// явно, а не только по россыпи единичных логов дропов. Сводка логируется
	// по факту доставки, поэтому события, отброшенные до начала Close,
	// в неё попадают.
	if n := b.dropped.Load(); n > 0 {
		b.log.Warn("события аудита отброшены во время работы", zap.Int64("dropped", n))
	}
}
