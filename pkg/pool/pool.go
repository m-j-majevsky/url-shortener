// Package pool реализует типобезопасный пул переиспользуемых объектов.
//
// Стандартный sync.Pool хранит значения как any: каждый Get требует
// type assertion (obj := pool.Get().(*bytes.Buffer)), а сброс состояния
// перед возвратом объекта в пул остаётся на совести вызывающего — забудут
// Reset() перед Put, и следующий Get вернёт «грязный» объект, причём ошибка
// проявляется не сразу: свежесозданный объект выглядит как «почти пустой»,
// и первые прогоны оказываются зелёными.
//
// Pool закрывает обе проблемы:
//
//   - Get возвращает готовый объект типа T без кастов: тип известен
//     на этапе компиляции;
//   - сброс состояния выполняет сам Put: забыть его невозможно.
//
// Пул параметризуется типом указателя (например, *audit.AuditEvent): методы
// Reset(), сгенерированные утилитой cmd/reset, объявлены с приёмником-указателем,
// поэтому в множество методов значения они не входят — тип-параметр обязан быть
// указателем. Пул допускает и иные типы, у которых Reset() объявлен в их
// собственном множестве методов.
//
// Механику sync.Pool (шардирование по P, ручной GC-цикл) обёртка не
// переизобретает: она добавляет типобезопасность и гарантированный сброс.
package pool

import (
	"reflect"
	"sync"
)

// Resetter — контракт объекта, пригодного для хранения в Pool: тип должен
// уметь сбрасывать своё состояние к начальным значениям.
//
// Метод Reset() без параметров и результатов — ровно тот контракт, который
// генерирует утилита cmd/reset для структур с маркером // generate:reset;.
type Resetter interface {
	Reset()
}

// Pool — потокобезопасный пул объектов одного конкретного типа T.
//
// Использование:
//
//	p := pool.New(func() *AuditEvent { return &AuditEvent{} })
//	event := p.Get()
//	// ... заполнение и использование event ...
//	p.Put(event) // Reset() выполняется здесь же, перед возвратом в пул
type Pool[T Resetter] struct {
	p sync.Pool
}

// New создаёт пул. Аргумент factory — фабрика, создающая новые объекты,
// когда пул пуст (аналог поля New у sync.Pool). Фабрика обязана возвращать
// готовый к использованию ненулевой объект. Вызываться она может
// конкурентно — Get допустим из нескольких горутин одновременно, — поэтому
// сама фабрика обязана быть потокобезопасной.
//
// Паника при nil-фабрике и при возвращённой фабрикой nil — намеренная:
// sync.Pool в этом случае вернул бы из Get нулевое значение (для указателя —
// nil), и такой nil выстрелил бы далеко от места ошибки. Здесь оба нарушения
// вскрываются сразу: в New — на этапе создания пула, в Get — на первом же
// обращении к пустому пулу.
func New[T Resetter](factory func() T) *Pool[T] {
	if factory == nil {
		panic("pool.New: фабрика объектов не может быть nil")
	}
	return &Pool[T]{
		p: sync.Pool{
			New: func() any {
				obj := factory()
				if isNil(obj) {
					panic("pool.New: фабрика вернула nil — объекты пула не могут быть нулевыми")
				}
				return obj
			},
		},
	}
}

// Get возвращает объект из пула; если пул пуст, объект создаёт фабрика,
// переданная в New. Возвращаемый объект готов к заполнению: его состояние
// сброшено либо при предыдущем Put, либо фабрикой.
func (p *Pool[T]) Get() T {
	return p.p.Get().(T)
}

// Put возвращает объект в пул, предварительно сбрасывая его состояние:
// Reset() вызывается до помещения в пул, поэтому забытый сброс невозможен.
//
// После Put объект считается принадлежащим пулу: использовать его больше
// нельзя — как и у sync.Pool.
//
// Паника при nil — намеренная: молча игнорировать nil значило бы скрывать
// ошибку вызывающего, а сбрасывать нечего.
func (p *Pool[T]) Put(obj T) {
	if isNil(obj) {
		panic("pool.Put: nil нельзя помещать в пул")
	}
	obj.Reset()
	p.p.Put(obj)
}

// isNil определяет, является ли значение «пустым» — nil для типов, которые
// это допускают: указателей, интерфейсов, слайсов, мап, каналов и функций.
//
// Прямое сравнение any(value) == nil здесь не годится: типизированный nil
// (например, (*testObject)(nil)) при превращении в any даёт непустой
// интерфейс с информацией о типе, и сравнение ошибочно даёт false —
// классическая ловушка интерфейсов в Go. Поэтому для типов, допускающих
// nil, пустота проверяется через reflection, а нулевой интерфейс ловится
// отдельным сравнением (для T-интерфейсных типов этого достаточно: ValueOf
// разворачивает интерфейс до динамического типа, и типизированный nil внутри
// интерфейса тоже распознаётся веткой reflect.Pointer).
func isNil[T any](value T) bool {
	if any(value) == nil {
		return true
	}
	v := reflect.ValueOf(value)
	kind := v.Kind()
	// Проверка оформлена через if, а не switch по Kind: анализатор exhaustive требует
	// полноты switch по перечислимым типам, а перечислять все два десятка
	// неинтересных видов ради шести nil-способных — ложная цель. Здесь смысл
	// не «разбор вариантов Kind», а проверка принадлежности множеству
	// nil-способных видов — if выражает это точнее.
	if kind == reflect.Pointer || kind == reflect.UnsafePointer ||
		kind == reflect.Map || kind == reflect.Slice ||
		kind == reflect.Chan || kind == reflect.Func {
		return v.IsNil()
	}
	return false
}
