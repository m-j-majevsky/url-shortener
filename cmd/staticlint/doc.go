// Package main реализует multichecker url-shortener — собственный
// объединённый статический анализатор проекта, собранный на базе
// multichecker из golang.org/x/tools/go/analysis.
//
// # Механизм запуска
//
// Линтер собирается в бинарник bin/staticlint и запускается из корня
// проекта со стандартными пакетными паттернами (как у go build и go vet):
//
//	make staticlint                      # эквивалентно двум командам ниже
//	go build -o bin/staticlint ./cmd/staticlint
//	bin/staticlint ./cmd/shortener ./cmd/loadgen ./internal/...  ./migrations
//
// Линтер не проверяет собственный main-пакет cmd/staticlint: его граф
// зависимостей (x/tools, staticcheck, errcheck, exhaustive) огромен и
// не является кодом проекта — включение его в паттерны резко повышает
// расход памяти (до OOM-kill на машинах с малой памятью) и время прогона.
// Пакетный список зашит в переменную STATICLINT_PKGS Makefile.
//
// Точка входа — multichecker.Main(analyzers...). Он регистрирует флаги
// для каждого анализатора (флаг вида <имя-анализатора>.<опция>), парсит
// командную строку, затем параллельно по пакетам запускает все
// переданные анализаторы: для каждого пакета строится type information
// и AST, результаты диагностики выводятся в формате go vet.
//
// Дополнительно поддержан собственный флаг:
//
//	-config path/to/config.json
//
// Путь задаётся аргументом командной строки. Файл — JSON вида
//
//	{
//	  "disabled": [
//	    "ST1000",
//	    "exhaustive"
//	  ]
//	}
//
// где перечислены имена анализаторов, исключаемые из прогона. Если флаг
// не указан, используется файл config.json в текущем каталоге, если он
// существует; при его отсутствии запускается полный набор. Явно заданный
// флаг имеет приоритет. Имена, не входящие в собранный набор, приводят
// к ошибке запуска — так опечатка в конфиге не даёт молча пропустить
// проверку.
//
// Значение флага читается предсканом os.Args до вызова multichecker.Main:
// полноценный flag.Parse выполняется внутри multichecker, поэтому до него
// наша опция вынимается вручную, а её регистрация на flag.CommandLine
// конфликтов не создаёт.
//
// # Состав набора анализаторов
//
//   - Стандартные анализаторы пакета golang.org/x/tools/go/analysis/passes:
//     vet-набор go vet (33 анализатора, список ниже) и shadow.
//
//   - Все анализаторы класса SA пакета staticcheck.io (honnef.co/go/tools):
//     отбор программный — по префиксу "SA" из staticcheck.Analyzers.
//     Класс SA охватывает проверки корректности кода: скрытые ошибки
//     логики, неверное использование стандартной библиотеки,
//     небезопасные шаблоны (использование после Close, потерянные
//     таймеры, неверные форматы строк и т. п.).
//
//   - Анализаторы класса ST пакета staticcheck.io, номера ST1000–ST1005
//     (по факту ST1000, ST1001, ST1003 и ST1005 — в нумерации staticcheck
//     есть пропуски): правила стиля и документации пакетов.
//
//   - Публичные анализаторы errcheck и exhaustive.
//
//   - Собственный анализатор exitinmain (пакет cmd/staticlint/exitanalyzer).
//
// # Стандартные анализаторы (passes)
//
//   - appends — проверяет корректность ...append(...) в variadic-вызовах
//     (случайный вместо intended e2 = append(e1)).
//
//   - asmdecl — сверяет ассемблерные объявления с сигнатурами Go.
//
//   - assign — находит присваивания, значения которых не используются.
//
//   - atomic — указывает на неатомарное использование sync/atomic.
//
//   - bools — упрощения булевых выражений (избыточные сравнения).
//
//   - buildtag — корректность директив //go:build и // +build.
//
//   - cgocall — передача указателей Go в вызовы cgo.
//
//   - composites — некомпозитные литералы нетипизированных типов
//     из чужих пакетов (vetwhitelisted для стандартной библиотеки).
//
//   - copylocks — копирование значений, содержащих sync.Locker.
//
//   - defers — ошибки defer (отложенный вызов проверяемого объекта).
//
//   - directive — корректность директив //go:... и //go:debug.
//
//   - errorsas — передача неуказателя в errors.As.
//
//   - framepointer — сброс кадра указателя в ассемблере.
//
//   - httpresponse — использование response до проверки ошибки.
//
//   - ifaceassert — бессмысленные interface-утверждения.
//
//   - loopclosure — захват переменных цикла в замыканиях и горутинах.
//
//   - lostcancel — потерянный cancel из context.WithCancel.
//
//   - nilfunc — сравнение функций с nil.
//
//   - printf — верификация printf-подобных вызовов и их обёрток.
//
//   - shift — сдвиги на ширину типа и со знаком.
//
//   - sigchanyzer — небуферизованный канал для signal.Notify.
//
//   - slog — ошибки ключ/значение в calls log/slog.
//
//   - stdmethods — неверные сигнатуры канонических методов
//     (Format, GobEncode, MarshalJSON и др.).
//
//   - stdversion — использование новых API стандартной библиотеки
//     при более старой go directive в go.mod.
//
//   - stringintconv — сомнительные преобразования int <-> string.
//
//   - structtag — дубликаты и ошибки в struct-тегах.
//
//   - testinggoroutine — вызов Fatal/Finish из горутин в тестах.
//
//   - tests — ошибки в файлах *_test.go (сигнатуры, дубликаты).
//
//   - timeformat — неверный формат времени (использование 1999).
//
//   - unmarshal — передача неверных типов в json/xml/yaml Unmarshal.
//
//   - unreachable — недостижимый код.
//
//   - unsafeptr — небезопасные преобразования unsafe.Pointer.
//
//   - unusedresult — игнорирование результатов вызовов, где это ошибка.
//
//   - shadow (дополнительно к vet-набору) — затенение переменных:
//     объявление переменной, перекрывающее внешнюю, из-за чего запись
//     может уходить «не туда». В дефолтный go vet не входит из-за
//     шумности, но входит в наш набор — проверка полезна, а уровень
//     шума контролируем конфигом.
//
// # Стилевые проверки staticcheck (ST1000–ST1005)
//
//   - ST1000 — наличие пакета комментария у пакета.
//   - ST1001 — отказ от dot-импорта (import . "...").
//   - ST1003 — имена в стиле initialisms (URL, ID, API).
//   - ST1005 — строки ошибок: без заглавной первой буквы и
//     без завершающей пунктуации.
//
// # Публичные анализаторы
//
//   - errcheck (github.com/kisielk/errcheck/errcheck) — находит
//     проигнорированные возвращённые ошибки: вызовы, возвращающие error,
//     но без проверки или с явным игнором. Анализатор помечен
//     upstream-автором как experimental. Флаги и встроенный список
//     исключений — см. раздел «Настройки errcheck».
//
//   - exhaustive (github.com/nishanths/exhaustive) — проверяет полноту
//     switch по значениям enum-типов и настраиваемые связанные правила
//     (default, отсутствие «забытых» вариантов при добавлении новых).
//
// # Настройки errcheck
//
// Анализатор errcheck в go/analysis-режиме управляется флагами blank,
// assert, exclude и excludeonly. По умолчанию (blank=false, assert=false)
// не проверяются явные присваивания в _ и непроверенные type assertions.
// Встроенный список исключений стандартной библиотеки сохранён (флаг
// excludeonly не выставляется).
//
// Исключения зашиты в бинарник: файл cmd/staticlint/errcheck.exclude
// подгружается go:embed и на старте выгружается во временный файл, путь
// которого устанавливается значением флага -errcheck.exclude до парсинга
// командной строки. Явно переданный флаг перекрывает встроенный список.
// Список сейчас содержит одну запись — (io.ReadCloser).Close: игнор
// ошибки Close тела HTTP-ответа после его чтения или выброса.
//
// Тестовый шум гасится не списком, а явностью: в тестовых файлах
// игнорируемые вызовы оформлены как defer func() { _ = x.Close() }()
// — осознанный игнор, который errcheck не помечает.
//
// # Собственный анализатор
//
//   - exitinmain (cmd/staticlint/exitanalyzer) — запрещает прямой
//     вызов os.Exit в функции main пакета main. Мотивация: прямой выход
//     из main теряет deferred-вызовы (graceful shutdown, сохранение
//     состояния) и делает пакет main непригодным для встраивания.
//     Аварийное завершение допустимо через log.Fatal: он вызывает
//     os.Exit внутри библиотеки, что прямым вызовом не считается.
//     Сгенерированные go test обёртки тестовых бинарей — пакеты
//     с путём, оканчивающимся на .test (их main заканчивается вызовом
//     os.Exit(m.Run())) — пропускаются по построению.
//     Подробное описание — в godoc пакета exitanalyzer.
